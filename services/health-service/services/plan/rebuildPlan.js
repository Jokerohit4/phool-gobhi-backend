import { PrismaClient } from '@prisma/client';
import { generatePlan } from '../ledger/planGenerator.js';
import { currentNutritionTarget } from '../ledger/currentTarget.js';
import { getOnLayerKeys } from './layerState.js';
import { buildWorkoutSlots } from '../ledger/starterPlanService.js';
import { MAX_ACTIVE_PLAN_ITEMS, DECIMAL_PLACES, roundTo } from '../ledger/constants.js';
import { track } from '../../utils/analytics.js';

/**
 * Rebuilds the user's suggested plan rows from the on-layer keys and current
 * targets/slots; stable ids via (kind, layerKey, schedule, sourceRef ?? '').
 *
 * @param {import('@prisma/client').PrismaClient} prisma
 * @param {number} userId
 * @param {{reason: 'start'|'unlock'|'consent'|'setup'|'edit'|'supplements'|'migrate'}} options
 * @returns {Promise<{created: number, updated: number, deactivated: number, onLayerKeys: string[]}>}
 */
export async function rebuildPlan(prisma, userId, { reason } = {}) {
  // Get on-layer keys
  const onLayerKeys = await getOnLayerKeys(prisma, userId);

  // Load current targets, prescription, and supplement schedules
  const [target, prescription, supplementSchedules, healthGoal] = await Promise.all([
    currentNutritionTarget(prisma, userId),
    prisma.prescription.findUnique({ where: { userId } }),
    prisma.supplementSchedule.findMany({ where: { userId, active: true } }),
    prisma.healthGoal.findUnique({ where: { userId } }),
  ]);

  const targets = target
    ? {
        kcal: Number(target.kcal),
        proteinG: Number(target.proteinG),
        carbsG: Number(target.carbsG),
        fatG: Number(target.fatG),
        fibreG: Number(target.fibreG),
        waterMl: Number(target.waterMl),
        micros: target.micros || {},
      }
    : null;

  const workoutSlots = prescription?.workoutSlots ?? [];
  const stepsPerDay = prescription?.stepsPerDay ?? 6000;
  const sleepMinutes = prescription?.sleepMinutes ?? 420;

  const supplements = onLayerKeys.includes('supplements')
    ? supplementSchedules.map((s) => ({
        id: s.id,
        name: s.name,
        schedule: s.schedule,
        targetValue: s.targetValue,
      }))
    : [];

  // Generate desired rows
  const { items: desiredRows, trimmedFrom } = generatePlan({
    goals: healthGoal?.goals ?? [],
    diet: healthGoal?.diet ?? null,
    targets,
    hasDoctorItems: false, // Will be checked inside generatePlan
    unlockedLayerKeys: onLayerKeys,
    workoutSlots,
    stepsPerDay,
    supplements,
  });

  // Get existing active suggested items
  const existingSuggested = await prisma.planItem.findMany({
    where: { userId, origin: 'suggested', active: true },
  });

  // Get user/doctor items count for cap calculation
  const userDoctorCount = await prisma.planItem.count({
    where: { userId, active: true, origin: { in: ['user', 'doctor'] } },
  });
  const room = Math.max(0, MAX_ACTIVE_PLAN_ITEMS - userDoctorCount);

  // Match desired rows to existing by (kind, layerKey, schedule, sourceRef ?? '')
  const matchKey = (row) => `${row.kind}|${row.layerKey ?? ''}|${row.schedule ?? ''}|${row.sourceRef ?? ''}`;

  const existingByKey = new Map();
  for (const item of existingSuggested) {
    const key = matchKey({
      kind: item.kind,
      layerKey: item.layerKey,
      schedule: item.schedule,
      sourceRef: item.sourceRef,
    });
    existingByKey.set(key, item);
  }

  const created = [];
  const updated = [];
  const matchedKeys = new Set();

  // Process desired rows in order, respecting room limit
  let kept = 0;
  for (const desired of desiredRows) {
    if (kept >= room) break;
    const key = matchKey(desired);
    const existing = existingByKey.get(key);

    if (existing) {
      // Update in place - keep same id so completions survive
      await prisma.planItem.update({
        where: { id: existing.id },
        data: {
          title: desired.title,
          targetValue: desired.targetValue != null ? roundTo(desired.targetValue, DECIMAL_PLACES.nutrients) : null,
          schedule: desired.schedule,
          layerKey: desired.layerKey ?? null,
          nutrientKey: desired.nutrientKey ?? null,
          sourceRef: desired.sourceRef ?? null,
        },
      });
      updated.push(existing.id);
      matchedKeys.add(key);
    } else {
      // Create new
      const createdItem = await prisma.planItem.create({
        data: {
          userId,
          kind: desired.kind,
          title: desired.title,
          schedule: desired.schedule,
          origin: 'suggested',
          layerKey: desired.layerKey ?? null,
          nutrientKey: desired.nutrientKey ?? null,
          targetValue: desired.targetValue != null ? roundTo(desired.targetValue, DECIMAL_PLACES.nutrients) : null,
          sourceRef: desired.sourceRef ?? null,
          active: true,
          autoGenerated: true,
        },
      });
      created.push(createdItem.id);
    }
    kept++;
  }

  // Deactivate unmatched existing suggested items
  const toDeactivate = existingSuggested.filter((item) => {
    const key = matchKey({
      kind: item.kind,
      layerKey: item.layerKey,
      schedule: item.schedule,
      sourceRef: item.sourceRef,
    });
    return !matchedKeys.has(key);
  });

  let deactivated = 0;
  if (toDeactivate.length > 0) {
    await prisma.planItem.updateMany({
      where: { id: { in: toDeactivate.map((i) => i.id) } },
      data: { active: false },
    });
    deactivated = toDeactivate.length;
  }

  // Emit plan_built event
  track('plan_built', userId, {
    reason,
    on_layers: onLayerKeys.join(','),
    created: created.length,
    updated: updated.length,
    deactivated,
  });

  // Emit layer_turned_on for layers that newly have active suggested rows
  const previousActiveLayers = new Set(
    existingSuggested.filter((i) => i.layerKey).map((i) => i.layerKey)
  );
  const currentActiveLayers = new Set(
    [...desiredRows.slice(0, room)].filter((r) => r.layerKey).map((r) => r.layerKey)
  );
  for (const layerKey of currentActiveLayers) {
    if (!previousActiveLayers.has(layerKey)) {
      track('layer_turned_on', userId, { layer: layerKey, reason });
    }
  }

  return {
    created: created.length,
    updated: updated.length,
    deactivated,
    onLayerKeys,
  };
}