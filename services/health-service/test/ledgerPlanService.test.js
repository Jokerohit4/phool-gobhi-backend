test('with onLayerKeys only those layers are returned, and a null layerKey is dropped', async () => {
  const prisma = mockPrisma({
    planItem: {
      findMany: async () => [
        { id: 1, kind: 'habit', layerKey: 'water', schedule: 'daily', endsOn: null, completions: [] },
        { id: 2, kind: 'habit', layerKey: 'steps', schedule: 'daily', endsOn: null, completions: [] },
        { id: 3, kind: 'habit', layerKey: null, schedule: 'daily', endsOn: null, completions: [] },
        { id: 4, kind: 'habit', layerKey: 'own', schedule: 'daily', endsOn: null, completions: [] },
      ],
    },
  });
  const out = await getPlanForDate(prisma, { userId: 7, localDate: TODAY, today: TODAY, onLayerKeys: ['water', 'own'] });
  assert.deepEqual(out.items.map((i) => i.id).sort(), [1, 4]);
});

test('without onLayerKeys the layer filter is skipped (legacy callers)', async () => {
  const prisma = mockPrisma({
    planItem: {
      findMany: async () => [
        { id: 1, kind: 'habit', layerKey: 'water', schedule: 'daily', endsOn: null, completions: [] },
        { id: 3, kind: 'habit', layerKey: null, schedule: 'daily', endsOn: null, completions: [] },
      ],
    },
  });
  const out = await getPlanForDate(prisma, { userId: 7, localDate: TODAY, today: TODAY });
  assert.equal(out.total, 2);
});

test('an end date is inclusive, so the last day still counts', async () => {
  // "take the tablets until the 30th" includes the 30th. Using `<` here would
  // silently drop the final day of every course.
  const prisma = mockPrisma({
    planItem: {
      findMany: async () => [
        { id: 1, kind: 'doctor_medication', layerKey: 'medicine', schedule: 'daily', endsOn: TODAY, completions: [] },
      ],
    },
  });
  const out = await getPlanForDate(prisma, { userId: 7, localDate: TODAY, today: TODAY });
  assert.equal(out.total, 1, 'the end date itself must still be due');
  assert.equal(out.items[0].id, 1);
});

test('a day past the end date is not due', async () => {
  const prisma = mockPrisma({
    planItem: {
      findMany: async () => [
        { id: 1, kind: 'doctor_medication', layerKey: 'medicine', schedule: 'daily', endsOn: '2026-09-27', completions: [] },
      ],
    },
  });
  const out = await getPlanForDate(prisma, { userId: 7, localDate: TODAY, today: TODAY });
  assert.equal(out.total, 0);
});

test('a malformed end date does not expire the item forever', async () => {
  // An unpadded '2026-9-1' sorts below '2026-10-05', so before this was guarded,
  // one badly formatted date made every doctor's item vanish. Wrongly keeping an
  // item alive is the cheaper failure than wrongly deleting it.
  const prisma = mockPrisma({
    planItem: {
      findMany: async () => [
        { id: 1, kind: 'doctor_medication', layerKey: 'medicine', schedule: 'daily', endsOn: '2026-9-1', completions: [] },
      ],
    },
  });
  const out = await getPlanForDate(prisma, { userId: 7, localDate: TODAY, today: TODAY });
  assert.equal(out.total, 1, 'a bad endsOn must not hide a live item');
});

test('deactivating keeps the row, it does not delete it', async () => {
  // Past days reference these rows through their completions, and a frozen
  // score has to stay explicable.
  const prisma = mockPrisma({
    planItem: { findFirst: async () => ({ id: 3, active: true }) },
    update: async (a) => ({ id: 3, ...a.data }),
  });
  const out = await deactivateItem(prisma, { userId: 7, planItemId: 3 });
  assert.equal(out.active, false);
});
