import { test } from 'node:test';
import assert from 'node:assert/strict';

import {
  addUserEnteredItem,
  completeItem,
  deactivateItem,
  getPlanForDate,
  isDueOn,
  regenerateSuggestions,
} from '../services/ledger/ledgerPlanService.js';
import { MAX_ACTIVE_PLAN_ITEMS } from '../services/ledger/constants.js';

const TODAY = '2026-09-28'; // a Monday

function mockPrisma(overrides = {}) {
  return {
    planItem: {
      create: async (a) => ({ id: 1, active: true, autoGenerated: false, ...a.data }),
      count: async () => 0,
      findFirst: async () => null,
      findMany: async () => [],
      update: async (a) => ({ id: a.where.id, ...a.data }),
      updateMany: async () => ({ count: 0 }),
      ...overrides.planItem,
    },
    planItemCompletion: {
      upsert: async (a) => ({ ...a.where.planItemId_localDate, ...a.create }),
      ...overrides.planItemCompletion,
    },
    ...overrides.rest,
  };
}

const TARGETS = { kcal: 2200, proteinG: 130, carbsG: 250, fatG: 70, fibreG: 30, waterMl: 3000, micros: { ironMg: 21 } };

// --- the doctor boundary ---------------------------------------------------

test('a user-entered item is origin user, never doctor', async () => {
  let data;
  const prisma = mockPrisma({ planItem: { create: async (a) => ((data = a.data), { id: 1, ...a.data }) } });
  await addUserEnteredItem(prisma, { userId: 7, title: 'Drink more water' });
  assert.equal(data.origin, 'user');
  assert.equal(data.prescribedBy, null);
  assert.equal(data.autoGenerated, false);
});

test('fromPrescription is the only route to origin doctor, and it keeps the typed text', async () => {
  let data;
  const prisma = mockPrisma({ planItem: { create: async (a) => ((data = a.data), { id: 1, ...a.data }) } });
  await addUserEnteredItem(prisma, {
    userId: 7,
    title: 'Metformin 500mg twice daily',
    fromPrescription: true,
    prescribedBy: 'Dr Rao',
  });
  // The title is the user's own words off their prescription. There is no
  // medicine picker anywhere in this path, because a picker is us suggesting a
  // dose.
  assert.equal(data.origin, 'doctor');
  assert.equal(data.title, 'Metformin 500mg twice daily');
  assert.equal(data.prescribedBy, 'Dr Rao');
});

test('prescription details are ignored unless fromPrescription is set', async () => {
  // A client that posts prescribedBy without the flag gets a plain user item,
  // so nothing can be dressed up as a doctor's instruction.
  let data;
  const prisma = mockPrisma({ planItem: { create: async (a) => ((data = a.data), { id: 1, ...a.data }) } });
  await addUserEnteredItem(prisma, { userId: 7, title: 'Stretch', prescribedBy: 'Dr Fake' });
  assert.equal(data.origin, 'user');
  assert.equal(data.prescribedBy, null);
});

test('regenerating only ever writes origin suggested', async () => {
  const created = [];
  const prisma = mockPrisma({
    planItem: {
      count: async () => 0,
      updateMany: async () => ({ count: 3 }),
      create: async (a) => (created.push(a.data), { id: created.length, ...a.data }),
    },
  });
  await regenerateSuggestions(prisma, { userId: 7, goals: ['build_muscle'], targets: TARGETS });
  assert.ok(created.length > 0);
  for (const item of created) {
    assert.equal(item.origin, 'suggested');
    assert.equal(item.autoGenerated, true);
  }
});

test('regenerate soft-deletes suggested items and never touches user or doctor ones', async () => {
  let where;
  const prisma = mockPrisma({
    planItem: {
      count: async () => 0,
      updateMany: async (a) => ((where = a.where), { count: 3 }),
      create: async (a) => ({ id: 1, ...a.data }),
    },
  });
  await regenerateSuggestions(prisma, { userId: 7, goals: ['lose_fat'], targets: TARGETS });
  // Scoped to origin: 'suggested'. If this ever widened, "regenerate" would
  // delete a doctor's course of tablets, which would make the feature dangerous
  // rather than convenient.
  assert.deepEqual(where.origin, 'suggested');
  assert.equal(where.active, true);
});

// --- the active-item cap ---------------------------------------------------

test('a full plan refuses a new item instead of dropping something silently', async () => {
  const prisma = mockPrisma({ planItem: { count: async () => MAX_ACTIVE_PLAN_ITEMS } });
  await assert.rejects(
    () => addUserEnteredItem(prisma, { userId: 7, title: 'One more thing' }),
    /already has 20 active items/,
  );
});

test("a user's own items do not shrink the room available to suggestions", async () => {
  let created = 0;
  const prisma = mockPrisma({
    planItem: {
      // Two active items, both the user's own.
      count: async (a) => {
        if (a.where.origin === 'suggested') return 0;
        return a.where.origin?.in ? 2 : 2;
      },
      updateMany: async () => ({ count: 0 }),
      create: async (a) => (created += 1, { id: created, ...a.data }),
    },
  });
  const out = await regenerateSuggestions(prisma, { userId: 7, goals: ['build_muscle'], targets: TARGETS });
  // Room is 20 - 2 = 18, not 20 - 2 total, because the suggested items being
  // replaced were already counted in the 2.
  assert.equal(out.room, 18);
  assert.equal(out.kept, 2);
});

test('when there is no room, nothing is created and the drop is reported', async () => {
  const prisma = mockPrisma({
    planItem: {
      count: async () => 25,
      updateMany: async () => ({ count: 0 }),
      create: async () => ({ id: 1 }),
    },
  });
  const out = await regenerateSuggestions(prisma, { userId: 7, goals: ['build_muscle'], targets: TARGETS });
  assert.equal(out.created, 0);
  assert.equal(out.room, 0);
  assert.ok(out.dropped > 0);
});

