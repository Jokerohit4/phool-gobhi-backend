// Plan items: what the plan says, who said it, and whether it happened.
//
// Run with: node --experimental-test-module-mocks --test
import { test } from 'node:test';
import assert from 'node:assert/strict';

import {
  addUserEnteredItem,
  completeItem,
  uncompleteItem,
  deactivateItem,
  getPlanForDate,
  isDueOn,
  PLAN_ITEM_KINDS,
} from '../services/ledger/ledgerPlanService.js';
import { MAX_ACTIVE_PLAN_ITEMS, LATE_LOGGING_WINDOW_DAYS } from '../services/ledger/constants.js';

const TODAY = '2026-09-28'; // a Monday

function mockPrisma(overrides = {}) {
  return {
    planItem: {
      create: async (a) => ({ id: 1, active: true, autoGenerated: false, ...a.data }),
      count: async () => 0,
      findFirst: async () => null,
      findMany: async () => [],
      update: async (a) => ({ id: a.where.id, ...a.data }),
      updateMany: async () => ({ count: 0 }),
      ...overrides.planItem,
    },
    planItemCompletion: {
      upsert: async (a) => ({ ...a.where.planItemId_localDate, ...a.create }),
      deleteMany: async () => ({ count: 0 }),
      ...overrides.planItemCompletion,
    },
    ...overrides.rest,
  };
}

// --- the doctor boundary ---------------------------------------------------

test('a user-entered item is origin user and lands on the own layer', async () => {
  let data;
  const prisma = mockPrisma({ planItem: { create: async (a) => ((data = a.data), { id: 1, ...a.data }) } });
  await addUserEnteredItem(prisma, { userId: 7, title: 'Drink more water' });
  assert.equal(data.origin, 'user');
  assert.equal(data.layerKey, 'own');
  assert.equal(data.prescribedBy, null);
  assert.equal(data.autoGenerated, false);
});

test('fromPrescription is the only route to origin doctor, and it keeps the typed text', async () => {
  let data;
  const prisma = mockPrisma({ planItem: { create: async (a) => ((data = a.data), { id: 1, ...a.data }) } });
  await addUserEnteredItem(prisma, {
    userId: 7,
    title: 'Metformin 500mg twice daily',
    fromPrescription: true,
    prescribedBy: 'Dr Rao',
  });
  // The title is the user's own words off their prescription. There is no
  // medicine picker anywhere in this path, because a picker is us suggesting a
  // dose.
  assert.equal(data.origin, 'doctor');
  assert.equal(data.layerKey, 'medicine');
  assert.equal(data.title, 'Metformin 500mg twice daily');
  assert.equal(data.prescribedBy, 'Dr Rao');
});

test('prescription details are ignored unless fromPrescription is set', async () => {
  // A client that posts prescribedBy without the flag gets a plain user item,
  // so nothing can be dressed up as a doctor's instruction.
  let data;
  const prisma = mockPrisma({ planItem: { create: async (a) => ((data = a.data), { id: 1, ...a.data }) } });
  await addUserEnteredItem(prisma, { userId: 7, title: 'Stretch', prescribedBy: 'Dr Fake' });
  assert.equal(data.origin, 'user');
  assert.equal(data.layerKey, 'own');
  assert.equal(data.prescribedBy, null);
});

