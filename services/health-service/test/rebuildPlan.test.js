// rebuildPlan — the ONE place suggested rows are (re)written (one-plan UB1).
//
// Properties pinned here:
//   1. It creates the generated set (per slot, rest, water, steps, sleep,
//      supplements) from the on-layer keys + the prescription/target.
//   2. It is idempotent: a rebuild whose inputs already match writes nothing.
//   3. Drift updates in place (title/targetValue only), keeping the row id, so
//      ticks survive.
//   4. Rows whose layer turned off are deactivated, never deleted.
//   5. User and doctor rows are never read into the diff, let alone touched.
//   6. The live user/doctor count caps how many suggested rows are created.
//   7. It never emits a doctor-sourced row.
//
// getOnLayerKeys (a 501 stub in layerState.js) and the analytics sink are
// mocked; everything else runs for real, so the generator's output shape is
// genuinely exercised.
//
// Run with: node --experimental-test-module-mocks --test
import { test, mock } from 'node:test';
import assert from 'node:assert/strict';

const state = {
  onLayerKeys: ['workout', 'water'],
  tracked: [],
};

mock.module('../services/plan/layerState.js', {
  exports: {
    getOnLayerKeys: async () => state.onLayerKeys,
  },
});

mock.module('../utils/analytics.js', {
  exports: {
    track: (event, userId, props) => state.tracked.push({ event, userId, props }),
    default: {},
  },
});

const { rebuildPlan } = await import('../services/plan/rebuildPlan.js');
const { MAX_ACTIVE_PLAN_ITEMS } = await import('../services/ledger/constants.js');

function fakePrisma({
  prescription = null,
  target = null,
  supplements = [],
  existing = [],
  userDoctorCount = 0,
} = {}) {
  const created = [];
  const updated = [];
  const calls = {
    count: 0,
    countArgs: [],
    findMany: 0,
    findManyArgs: [],
    supplementFindMany: 0,
    transaction: 0,
  };
  const prisma = {
    nutritionTarget: { findFirst: async () => target },
    prescription: { findUnique: async () => prescription },
    supplementSchedule: {
      findMany: async (args) => {
        calls.supplementFindMany += 1;
        return supplements;
      },
    },
    planItem: {
      count: async (args) => {
        calls.count += 1;
        calls.countArgs.push(args);
        if (args?.where?.origin?.in) return userDoctorCount;
        return 0;
      },
      findMany: async (args) => {
        calls.findMany += 1;
        calls.findManyArgs.push(args);
        return existing;
      },
      create: async ({ data }) => {
        created.push(data);
        return { id: created.length, ...data };
      },
      update: async ({ where, data }) => {
        updated.push({ id: where.id, ...data });
        return { id: where.id, ...data };
      },
    },
    $transaction: async (fn) => {
      calls.transaction += 1;
      return fn(prisma);
    },
  };
  return { prisma, created, updated, calls };
}

const slot = (weekday, title) => ({ weekday, templateId: 1, title, level: 'beginner' });

// ---- creation --------------------------------------------------------------

test('a workout+water rebuild creates the slot rows, a rest row and water', async () => {
  state.onLayerKeys = ['workout', 'water'];
  state.tracked = [];
  const { prisma, created, calls } = fakePrisma({
    prescription: { workoutSlots: [slot(0, 'Session 1'), slot(2, 'Session 2')] },
  });

  const out = await rebuildPlan(prisma, 7, { reason: 'start' });

  const keys = created.map((c) => `${c.kind}|${c.layerKey}|${c.schedule}`);
  // Two Mon/Wed workouts (weekdays 0,2 -> schedules '1','3'), a rest row on
  // '2,4,5,6,7', and the water habit.
  assert.ok(keys.includes('workout|workout|1'));
  assert.ok(keys.includes('workout|workout|3'));
  assert.ok(keys.includes('rest|workout|2,4,5,6,7'));
  assert.ok(keys.includes('habit|water|daily'));
  assert.equal(out.created, created.length);
  assert.equal(out.updated, 0);
  assert.equal(out.deactivated, 0);
  assert.deepEqual(out.onLayerKeys, ['workout', 'water']);
  assert.equal(calls.transaction, 1, 'the diff is applied in one transaction');
});

test('every created row is origin suggested and autoGenerated, with its layerKey', async () => {
  state.onLayerKeys = ['workout', 'water', 'steps', 'sleep'];
  state.tracked = [];
  const { prisma, created } = fakePrisma({
    prescription: { workoutSlots: [slot(1, 'Legs')], stepsPerDay: 9000, sleepMinutes: 480 },
    target: { waterMl: 3000 },
  });

  await rebuildPlan(prisma, 7, { reason: 'consent' });

  assert.ok(created.length > 0);
  for (const row of created) {
    assert.equal(row.origin, 'suggested');
    assert.equal(row.autoGenerated, true);
    assert.equal(row.active, true);
    assert.ok(row.layerKey, 'a suggested row with no layerKey could never be deactivated');
  }
  // The prescription and target drive the numbers, not the defaults.
  assert.ok(created.some((c) => c.layerKey === 'steps' && /9,000 steps/.test(c.title)));
  assert.ok(created.some((c) => c.layerKey === 'sleep' && c.title === 'Sleep 8 h'));
  assert.ok(created.some((c) => c.layerKey === 'water' && c.title === 'Drink 3.0 L water' && Number(c.targetValue) === 3000));
});

// ---- idempotence -----------------------------------------------------------

test('a rebuild whose inputs already match writes nothing', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const existing = [
    { id: 11, kind: 'habit', layerKey: 'water', schedule: 'daily', sourceRef: null, title: 'Drink 2.5 L water', targetValue: 2500 },
  ];
  const { prisma, created, updated, calls } = fakePrisma({ existing });

  const out = await rebuildPlan(prisma, 7, { reason: 'unlock' });

  assert.equal(created.length, 0);
  assert.equal(updated.length, 0);
  assert.equal(calls.transaction, 0, 'an already-current plan must not open a transaction');
  assert.deepEqual(out, { created: 0, updated: 0, deactivated: 0, onLayerKeys: ['water'] });
});

// ---- drift updates in place ------------------------------------------------

test('a title/target drift updates the existing row, keeping its id', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const existing = [
    { id: 11, kind: 'habit', layerKey: 'water', schedule: 'daily', sourceRef: null, title: 'Drink 2.0 L water', targetValue: 2000 },
  ];
  const { prisma, created, updated } = fakePrisma({ existing });

  await rebuildPlan(prisma, 7, { reason: 'setup' });

  assert.equal(created.length, 0);
  assert.equal(updated.length, 1);
  assert.equal(updated[0].id, 11, 'the row id must survive so its ticks survive');
  assert.equal(updated[0].title, 'Drink 2.5 L water');
  assert.equal(Number(updated[0].targetValue), 2500);
});

test('a Decimal-equal targetValue does not count as drift', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  // The DB hands back a Decimal; Number('2500.00') === 2500, so nothing drifts.
  const existing = [
    { id: 11, kind: 'habit', layerKey: 'water', schedule: 'daily', sourceRef: null, title: 'Drink 2.5 L water', targetValue: '2500.00' },
  ];
  const { prisma, updated } = fakePrisma({ existing });

  await rebuildPlan(prisma, 7, { reason: 'unlock' });

  assert.equal(updated.length, 0);
});

// ---- deactivation ----------------------------------------------------------

test('a row whose layer turned off is deactivated, never deleted', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const existing = [
    { id: 20, kind: 'habit', layerKey: 'steps', schedule: 'daily', sourceRef: null, title: 'Walk 8,000 steps', targetValue: 8000 },
    { id: 11, kind: 'habit', layerKey: 'water', schedule: 'daily', sourceRef: null, title: 'Drink 2.5 L water', targetValue: 2500 },
  ];
  const { prisma, created, updated } = fakePrisma({ existing });

  const out = await rebuildPlan(prisma, 7, { reason: 'unlock' });

  assert.equal(created.length, 0);
  assert.equal(out.updated, 0, 'nothing drifted, so no row was rewritten');
  assert.equal(out.deactivated, 1);
  // Deactivation is a soft update, not a delete — there is no delete path in
  // the fake at all, so the row can only ever be found among the updates, with
  // active:false.
  const dead = updated.find((r) => r.id === 20);
  assert.equal(dead.active, false);
  assert.equal(updated.some((r) => r.id === 11), false, 'the still-good water row was left alone');
  assert.equal(out.onLayerKeys.includes('steps'), false);
});

// ---- user/doctor rows are out of scope -------------------------------------

test('the diff reads and counts only around suggested vs user/doctor, never mixes them', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const { prisma, calls } = fakePrisma({ existing: [] });

  await rebuildPlan(prisma, 7, { reason: 'edit' });

  // The existing-rows query is scoped to suggested, so a user row can never
  // look deactivate-able.
  assert.deepEqual(calls.findManyArgs[0].where.origin, 'suggested');
  assert.equal(calls.findManyArgs[0].where.active, true);
  // The room cap counts the live user/doctor rows (and only those).
  assert.deepEqual(calls.countArgs[0].where.origin.in, ['user', 'doctor']);
});

test('the room cap limits how many suggested rows are created', async () => {
  // MAX is 20; 19 live user/doctor rows leave room for exactly one suggested.
  state.onLayerKeys = ['steps', 'sleep'];
  state.tracked = [];
  const { prisma, created } = fakePrisma({ userDoctorCount: MAX_ACTIVE_PLAN_ITEMS - 1 });

  const out = await rebuildPlan(prisma, 7, { reason: 'edit' });

  assert.equal(created.length, 1);
  assert.equal(out.created, 1);
  assert.equal(created[0].layerKey, 'steps', 'the desired order is kept, sliced by free room');
});

test('a user with no room left gets no suggested rows at all', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const { prisma, created, calls } = fakePrisma({ userDoctorCount: MAX_ACTIVE_PLAN_ITEMS });

  const out = await rebuildPlan(prisma, 7, { reason: 'edit' });

  assert.equal(created.length, 0);
  assert.equal(out.created, 0);
  assert.equal(calls.transaction, 0);
});

// ---- supplements -----------------------------------------------------------

test('supplement rows are one-per-schedule, keyed by sourceRef, and only when the layer is on', async () => {
  state.onLayerKeys = ['supplements'];
  state.tracked = [];
  const { prisma, created, calls } = fakePrisma({
    supplements: [{ id: 3, name: 'Vitamin D' }, { id: 5, name: 'Omega 3' }],
  });

  await rebuildPlan(prisma, 7, { reason: 'supplements' });

  assert.equal(calls.supplementFindMany, 1);
  const supp = created.filter((c) => c.layerKey === 'supplements');
  assert.equal(supp.length, 2);
  assert.deepEqual(supp.map((c) => c.sourceRef).sort(), ['supplement:3', 'supplement:5']);
});

test('the supplements layer off does not even read the schedules', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const { prisma, created, calls } = fakePrisma({
    supplements: [{ id: 3, name: 'Vitamin D' }],
  });

  await rebuildPlan(prisma, 7, { reason: 'unlock' });

  assert.equal(calls.supplementFindMany, 0, 'layer off must not query supplement schedules');
  assert.equal(created.some((c) => c.layerKey === 'supplements'), false);
});

test('a renamed schedule updates its row in place via sourceRef, not a twin', async () => {
  state.onLayerKeys = ['supplements'];
  state.tracked = [];
  const existing = [
    { id: 31, kind: 'habit', layerKey: 'supplements', schedule: 'daily', sourceRef: 'supplement:3', title: 'Vit D', targetValue: null },
  ];
  const { prisma, created, updated } = fakePrisma({
    supplements: [{ id: 3, name: 'Vitamin D3' }],
    existing,
  });

  await rebuildPlan(prisma, 7, { reason: 'supplements' });

  assert.equal(created.length, 0, 'the row must be updated, not duplicated');
  assert.equal(updated.length, 1);
  assert.equal(updated[0].id, 31);
  assert.equal(updated[0].title, 'Vitamin D3');
});

// ---- the medical line ------------------------------------------------------

test('a fully-open rebuild never emits a doctor-sourced row', async () => {
  state.onLayerKeys = ['workout', 'water', 'steps', 'sleep', 'supplements', 'health', 'medicine', 'own'];
  state.tracked = [];
  const { prisma, created } = fakePrisma({
    prescription: { workoutSlots: [slot(0, 'A'), slot(2, 'B'), slot(4, 'C')], stepsPerDay: 8000, sleepMinutes: 450 },
    supplements: [{ id: 1, name: 'Creatine' }],
    target: { waterMl: 3000 },
  });

  await rebuildPlan(prisma, 7, { reason: 'migrate' });

  for (const row of created) {
    assert.equal(row.origin, 'suggested');
    assert.notEqual(row.layerKey, 'medicine');
    assert.notEqual(row.layerKey, 'health');
  }
});

// ---- analytics -------------------------------------------------------------

test('plan_built always fires, layer_turned_on only for a freshly-on layer', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const { prisma } = fakePrisma({ existing: [] });

  await rebuildPlan(prisma, 7, { reason: 'start' });

  const built = state.tracked.filter((t) => t.event === 'plan_built');
  assert.equal(built.length, 1);
  assert.equal(built[0].props.reason, 'start');
  // Water had no rows before, so it just turned on.
  assert.deepEqual(state.tracked.filter((t) => t.event === 'layer_turned_on').map((t) => t.props.layer), ['water']);
});

test('a layer that already had rows does not re-fire layer_turned_on', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const existing = [
    { id: 11, kind: 'habit', layerKey: 'water', schedule: 'daily', sourceRef: null, title: 'Drink 2.5 L water', targetValue: 2500 },
  ];
  const { prisma } = fakePrisma({ existing });

  await rebuildPlan(prisma, 7, { reason: 'unlock' });

  assert.equal(state.tracked.some((t) => t.event === 'layer_turned_on'), false);
  assert.equal(state.tracked.some((t) => t.event === 'plan_built'), true);
});

// ---- the reason is only a label --------------------------------------------

test('the reason never changes the diff', async () => {
  state.onLayerKeys = ['water'];
  state.tracked = [];
  const a = fakePrisma({ existing: [] });
  state.onLayerKeys = ['water'];
  await rebuildPlan(a.prisma, 7, { reason: 'start' });

  const b = fakePrisma({ existing: [] });
  await rebuildPlan(b.prisma, 7, { reason: 'edit' });

  assert.equal(a.created.length, b.created.length);
  assert.deepEqual(
    a.created.map((c) => `${c.kind}|${c.layerKey}|${c.schedule}`).sort(),
    b.created.map((c) => `${c.kind}|${c.layerKey}|${c.schedule}`).sort(),
  );
});
